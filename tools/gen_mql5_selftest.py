#!/usr/bin/env python3
"""Generate mql5/Scripts/VeritasChain/VCP_SelfTest.mq5 from test-vectors/vectors.json.

Strings are emitted as ASCII literals plus ShortToString(0x....) for every other
UTF-16 code unit, so the .mq5 file is plain ASCII whatever encoding MetaEditor uses.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "python" / "src"))
import veritaschain_vcp as vcp  # noqa: E402
from veritaschain_vcp import jcs  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
V = json.loads((ROOT / "test-vectors" / "vectors.json").read_text(encoding="utf-8"))


def mql_str(s: str) -> str:
    parts: list[str] = []
    lit = ""
    for unit in [int.from_bytes(s.encode("utf-16-be")[i:i + 2], "big") for i in range(0, len(s.encode("utf-16-be")), 2)]:
        ch = chr(unit) if unit < 0xD800 or unit > 0xDFFF else None
        if ch is not None and 0x20 <= unit < 0x7F and ch not in '"\\':
            lit += ch
        else:
            if lit:
                parts.append(f'"{lit}"')
                lit = ""
            parts.append(f"ShortToString(0x{unit:04X})")
    if lit or not parts:
        parts.append(f'"{lit}"')
    return " + ".join(parts)


class Emitter:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.n = 0

    def var(self) -> str:
        self.n += 1
        return f"j{self.n}"

    def emit(self, v) -> str:
        """Emit code building v; return the expression that refers to it."""
        if v is None:
            return "VcpNull()"
        if v is True or v is False:
            return f"VcpBool({'true' if v else 'false'})"
        if isinstance(v, int):
            return f'VcpInt(StringToInteger("{v}"))'
        if isinstance(v, str):
            return f"VcpStr({mql_str(v)})"
        if isinstance(v, float):
            raise ValueError("MQL5 builder has no floating-point numbers")
        name = self.var()
        if isinstance(v, list):
            self.lines.append(f"   CVcpJson *{name} = VcpArr();")
            for item in v:
                self.lines.append(f"   {name}.Add({self.emit(item)});")
        else:
            self.lines.append(f"   CVcpJson *{name} = VcpObj();")
            for k, item in v.items():
                self.lines.append(f"   {name}.Put({mql_str(k)}, {self.emit(item)});")
        return name


def main() -> None:
    out: list[str] = []
    out.append("""//+------------------------------------------------------------------+
//| VCP_SelfTest.mq5 - checks VCP.mqh against test-vectors/vectors.json |
//| Generated by tools/gen_mql5_selftest.py. Do not edit by hand.      |
//| Run as a script in MetaTrader 5; results go to the Experts log.    |
//+------------------------------------------------------------------+
#property script_show_inputs
#include <VeritasChain/VCP.mqh>

int g_pass = 0, g_fail = 0;

void Expect(const string name, const string got, const string want)
  {
   if(got == want) g_pass++;
   else
     {
      g_fail++;
      PrintFormat("FAIL %s\\n  got:  %s\\n  want: %s", name, got, want);
     }
  }

void ExpectTrue(const string name, const bool ok)
  {
   if(ok) g_pass++;
   else { g_fail++; PrintFormat("FAIL %s", name); }
  }

//--- the non-empty lines of a file, split on "\\n"; -1 if it cannot be opened
int ReadLines(const string f, string &lines[])
  {
   ArrayResize(lines, 0);
   int h = FileOpen(f, FILE_READ | FILE_BIN | FILE_SHARE_READ);
   if(h == INVALID_HANDLE) return -1;
   uchar b[];
   ArrayResize(b, (int)FileSize(h));
   uint n = FileReadArray(h, b, 0, (int)FileSize(h));
   FileClose(h);
   if(n == 0) return 0;
   string parts[];
   int k = StringSplit(CharArrayToString(b, 0, (int)n, CP_UTF8), '\\n', parts);
   int m = 0;
   for(int i = 0; i < k; i++)
      if(parts[i] != "")
        {
         ArrayResize(lines, m + 1);
         lines[m++] = parts[i];
        }
   return m;
  }

//--- append raw text (UTF-8) to a file, creating it
void AppendRaw(const string f, const string s)
  {
   int h = FileOpen(f, FILE_READ | FILE_WRITE | FILE_BIN);
   if(h == INVALID_HANDLE) return;
   FileSeek(h, 0, SEEK_END);
   uchar b[];
   int n = VcpUtf8(s, b);
   if(n > 0) FileWriteArray(h, b, 0, n);
   FileClose(h);
  }

long SizeOf(const string f)
  {
   int h = FileOpen(f, FILE_READ | FILE_BIN | FILE_SHARE_READ);
   if(h == INVALID_HANDLE) return -1;
   long n = (long)FileSize(h);
   FileClose(h);
   return n;
  }
""")
    # JCS vectors without floating-point numbers
    body: list[str] = []
    for i, vec in enumerate(V["jcs"]):
        value = json.loads(vec["input"])
        try:
            e = Emitter()
            expr = e.emit(value)
        except ValueError:
            continue
        body.append(f"   //--- JCS vector {i}")
        body.append("   {")
        body.extend(e.lines)
        if expr.startswith("Vcp"):
            body.append(f"   CVcpJson *jcs{i} = {expr};")
            expr = f"jcs{i}"
        body.append(f'   Expect("jcs {i}", {expr}.Canonical(), {mql_str(vec["canonical"])});')
        body.append(f"   delete {expr};")
        body.append("   }")
    # events
    for i, row in enumerate(V["events"]):
        ev = row["event"]
        e = Emitter()
        h = e.emit(ev["Header"])
        p = e.emit(ev["Payload"])
        prev = ev["Security"].get("PrevHash", "")
        body.append(f"   //--- event {i}")
        body.append("   {")
        body.extend(e.lines)
        body.append(f'   Expect("event {i} header", {h}.Canonical(), {mql_str(row["canonical_header"])});')
        body.append(f'   Expect("event {i} payload", {p}.Canonical(), {mql_str(row["canonical_payload"])});')
        body.append(f'   Expect("event {i} hash", VcpEventHash({h}, {p}, "{prev}"), "{row["event_hash"]}");')
        body.append(f"   delete {h};")
        body.append(f"   delete {p};")
        body.append("   }")
    # writer: line format; resume after reopening, also when the Payload holds EventHash keys;
    # refusal of another chain and of an incomplete last line; continuing a chain in a new file
    evs = [r["event"] for r in V["events"]]
    hdr0 = evs[0]["Header"]
    A, C, P = hdr0["ActorID"], hdr0["ChainID"], hdr0["PolicyID"]
    trap = {"VCP-XREF": {"UpstreamParty": {"EventHash": "sha256:" + "ab" * 32}},
            "Z": {"Security": {"EventHash": "sha256:" + "cd" * 32, "HashAlgo": "SHA256"}}}
    plan = [(evs[0]["Header"], evs[0]["Payload"]), (evs[1]["Header"], trap),
            (evs[2]["Header"], evs[2]["Payload"]), (evs[3]["Header"], evs[3]["Payload"])]
    hashes, lines, prev = [], [], None
    for hd, pl in plan:
        eh = vcp.compute_event_hash(hd, pl, prev_hash=prev)
        sec = {"EventHash": "sha256:" + eh, "HashAlgo": "SHA256"}
        if prev:
            sec["PrevHash"] = "sha256:" + prev
        lines.append(jcs.canonicalize_str({"Header": hd, "Payload": pl, "Security": sec}))
        hashes.append(eh)
        prev = eh
    assert hashes[0] == V["events"][0]["event_hash"]

    def write(i, n):
        hd, pl = plan[i]
        e = Emitter(); e.n = n
        expr = e.emit(pl)
        body.extend(e.lines)
        body.append(f'   Expect("writer hash {i}", w.Write("{hd["EventType"]}", {expr}, StringToInteger("{hd["TimestampInt"]}"), "{hd["EventID"]}"), "{hashes[i]}");')

    body.append("   //--- CVcpWriter")
    body.append("   {")
    body.append('   string pre = "vcp_selftest-";')
    body.append('   string d23 = pre + "20261023.jsonl", d24 = pre + "20261024.jsonl", d25 = pre + "20261025.jsonl", odd = pre + "x-20261024.jsonl";')
    body.append("   FileDelete(d23); FileDelete(d24); FileDelete(d25); FileDelete(odd);")
    body.append("   CVcpWriter w;")
    body.append(f'   ExpectTrue("writer open", w.Open(d23, "{A}", "{C}", "{P}", 9, true));')
    body.append('   ExpectTrue("writer starts empty", w.NextSequence() == 0 && w.LastHash() == "");')
    write(0, 1000)
    write(1, 1100)
    body.append("   w.Close();")
    body.append(f'   ExpectTrue("writer reopen", w.Open(d23, "{A}", "{C}", "{P}", 9, true));')
    body.append('   ExpectTrue("writer resumes SequenceNum", w.NextSequence() == 2);')
    body.append(f'   Expect("writer resumes the last EventHash (Payload has EventHash keys)", w.LastHash(), "{hashes[1]}");')
    write(2, 1200)
    body.append("   w.Close();")
    body.append("   string got[];")
    body.append('   ExpectTrue("writer file has 3 lines", ReadLines(d23, got) == 3);')
    body.append("   if(ArraySize(got) == 3)")
    body.append("     {")
    for i in range(3):
        body.append(f'      Expect("writer line {i}", got[{i}], {mql_str(lines[i])});')
    body.append("     }")
    body.append(f'   ExpectTrue("writer refuses another ChainID", !w.Open(d23, "{A}", "other-chain", "{P}", 9, true));')
    body.append("   //--- an empty file for the 24th, a file of another name pattern, then the 25th continues from the 23rd")
    body.append("   AppendRaw(d24, \"\");")
    body.append(f"   AppendRaw(odd, {mql_str(lines[0][:40])});")
    body.append("   bool found = false; long lastSeq = -1; string lastHash = \"\";")
    body.append(f'   ExpectTrue("find previous", VcpFindPrevious(pre, ".jsonl", d25, "{A}", "{C}", found, lastSeq, lastHash));')
    body.append(f'   ExpectTrue("find previous: found in the 23rd", found && lastSeq == 2 && lastHash == "{hashes[2]}");')
    body.append(f'   ExpectTrue("writer opens a new file to continue", w.Open(d25, "{A}", "{C}", "{P}", 9, true, lastSeq + 1, lastHash));')
    body.append('   ExpectTrue("continued SequenceNum", w.NextSequence() == 3);')
    write(3, 1300)
    body.append("   w.Close();")
    body.append('   ExpectTrue("new file has 1 line", ReadLines(d25, got) == 1);')
    body.append(f'   if(ArraySize(got) == 1) Expect("writer line 3 (links to the previous file)", got[0], {mql_str(lines[3])});')
    body.append("   //--- an incomplete last line is refused and the file is left as it is")
    body.append(f"   AppendRaw(d25, {mql_str(lines[0][:25])});")
    body.append("   long before = SizeOf(d25);")
    body.append(f'   ExpectTrue("writer refuses an incomplete last line", !w.Open(d25, "{A}", "{C}", "{P}", 9, true));')
    body.append('   ExpectTrue("refused open leaves the file unchanged", SizeOf(d25) == before);')
    body.append("   FileDelete(d23); FileDelete(d24); FileDelete(d25); FileDelete(odd);")
    body.append("   }")
    # header builder and timestamps
    h0 = V["events"][0]["event"]["Header"]
    body.append("   //--- header builder")
    body.append(f'   CVcpJson *hb = VcpHeader("{h0["EventType"]}", "{h0["ActorID"]}", "{h0["ChainID"]}", {h0["SequenceNum"]}, '
                f'"{h0["PolicyID"]}", StringToInteger("{h0["TimestampInt"]}"), 9, "{h0["EventID"]}");')
    body.append(f'   Expect("header builder", hb.Canonical(), {mql_str(V["events"][0]["canonical_header"])});')
    body.append("   delete hb;")
    body.append('   Expect("iso ms", VcpIsoFromNs(StringToInteger("1791504000123456789"), 3), "2026-10-09T00:00:00.123Z");')
    body.append('   Expect("iso s", VcpIsoFromNs(StringToInteger("1791504000000000000"), 0), "2026-10-09T00:00:00Z");')
    body.append('   string u = VcpUuid7(StringToInteger("1250999896491"));')
    body.append('   ExpectTrue("uuid7 shape", StringLen(u) == 36 && StringSubstr(u, 14, 1) == "7" && StringSubstr(u, 0, 13) == "01234567-89ab");')
    # Merkle
    leaves = V["merkle"]["leaves"]
    body.append("   //--- Merkle (leaves are SHA-256 of the decimal strings 0..23)")
    body.append("   string leaves[];")
    body.append("   ArrayResize(leaves, 24);")
    body.append("   for(int i = 0; i < 24; i++) { uchar d[], h[]; VcpUtf8(IntegerToString(i), d); VcpSha256(d, h); leaves[i] = VcpHex(h); }")
    body.append(f'   Expect("leaf 0", leaves[0], "{leaves[0]}");')
    body.append(f'   Expect("leaf 23", leaves[23], "{leaves[23]}");')
    body.append("   string part[];")
    for n in range(1, 25):
        body.append(f"   ArrayResize(part, {n}); for(int i = 0; i < {n}; i++) part[i] = leaves[i];")
        body.append(f'   Expect("root {n}", VcpMerkleRoot(part), "{V["merkle"]["roots"][str(n)]}");')
    for n in (1, 2, 3, 5, 7, 8, 13, 24):
        root = V["merkle"]["roots"][str(n)]
        for i in range(n):
            proof = V["merkle"]["inclusion"][str(n)][str(i)]
            arr = f"pr_{n}_{i}"
            body.append("   {")
            body.append(f"   string {arr}[];")
            body.append(f"   ArrayResize({arr}, {len(proof)});")
            for j, x in enumerate(proof):
                body.append(f'   {arr}[{j}] = "{x}";')
            body.append(f'   ExpectTrue("inclusion {n}/{i}", VcpVerifyInclusion(leaves[{i}], {i}, {n}, {arr}, "{root}"));')
            if n > 1:
                body.append(f'   ExpectTrue("inclusion {n}/{i} wrong index", !VcpVerifyInclusion(leaves[{i}], {(i + 1) % n}, {n}, {arr}, "{root}"));')
            body.append("   }")
    out.append("void OnStart()\n  {")
    out.extend(body)
    out.append('   PrintFormat("VCP.mqh %s self-test: %d passed, %d failed", VCP_SDK_VERSION, g_pass, g_fail);')
    out.append("  }")
    out.append("//+------------------------------------------------------------------+")
    dst = ROOT / "mql5" / "Scripts" / "VeritasChain" / "VCP_SelfTest.mq5"
    dst.write_text("\n".join(out) + "\n", encoding="ascii")
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
